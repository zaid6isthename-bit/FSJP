-- MESHNOTE H2 Database Schema
-- File-based persistence at data/database/meshnotedb

CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(36) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    division VARCHAR(50) NOT NULL,
    semester INT NOT NULL,
    device_name VARCHAR(100) NOT NULL,
    discoverable BOOLEAN DEFAULT TRUE,
    sharing_enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shared_files (
    id VARCHAR(36) PRIMARY KEY,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    subject VARCHAR(100) NOT NULL,
    module VARCHAR(50) NOT NULL,
    semester INT NOT NULL,
    description VARCHAR(500),
    owner_user_id VARCHAR(36) NOT NULL,
    shared BOOLEAN DEFAULT TRUE,
    access_count INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transfers (
    id VARCHAR(36) PRIMARY KEY,
    file_id VARCHAR(36) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    direction VARCHAR(20) NOT NULL, -- DOWNLOAD or UPLOAD
    peer_node_id VARCHAR(36) NOT NULL,
    peer_name VARCHAR(100) NOT NULL,
    bytes_total BIGINT NOT NULL,
    bytes_transferred BIGINT DEFAULT 0,
    speed_bps BIGINT DEFAULT 0,
    status VARCHAR(30) NOT NULL, -- QUEUED, CONNECTING, DOWNLOADING, UPLOADING, COMPLETED, FAILED, CANCELLED, PAUSED
    error_message VARCHAR(500),
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    type VARCHAR(50) NOT NULL, -- PEER_JOINED, PEER_LEFT, TRANSFER_COMPLETED, TRANSFER_FAILED, FILE_SHARED, NETWORK_STATE
    title VARCHAR(200) NOT NULL,
    description VARCHAR(500) NOT NULL,
    read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS activity_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    event_type VARCHAR(50) NOT NULL, -- PEER_JOINED, PEER_LEFT, FILE_SHARED, FILE_DOWNLOADED, SHARING_PAUSED, SHARING_RESUMED
    title VARCHAR(200) NOT NULL,
    description VARCHAR(500) NOT NULL,
    peer_id VARCHAR(36),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
